cells.append(code(
    'if TRAIN_ON_KAGGLE:\n'
    '    import re\n'
    '\n'
    '    def _extract_boxed(text: str):\n'
    '        """Extract content from last \\\\boxed{} with nested-brace support."""\n'
    '        pos = text.rfind(r"\\boxed{")\n'
    '        if pos == -1:\n'
    '            return None\n'
    '        start = pos + len(r"\\boxed{")\n'
    '        depth, i = 1, start\n'
    '        while i < len(text) and depth > 0:\n'
    '            if text[i] == "{":\n'
    '                depth += 1\n'
    '            elif text[i] == "}":\n'
    '                depth -= 1\n'
    '            i += 1\n'
    '        return text[start : i - 1].strip() if depth == 0 else None\n'
    '\n'
    '    def _normalize(ans):\n'
    '        if not ans:\n'
    '            return ""\n'
    '        ans = ans.strip()\n'
    '        for tok in (r"\\\\,", r"\\,", r"\\\\!", r"\\!", r"\\\\ ", r"\\ ", r"\\text{", "}"):\n'
    '            ans = ans.replace(tok, "")\n'
    '        try:\n'
    '            val = float(ans.replace(",", ""))\n'
    '            if val == int(val) and abs(val) < 1e15:\n'
    '                return str(int(val))\n'
    '            return f"{val:.8g}"\n'
    '        except (ValueError, OverflowError):\n'
    '            pass\n'
    '        return ans.lower().replace(" ", "")\n'
    '\n'
    '    def _is_correct(pred, gold):\n'
    '        if pred is None:\n'
    '            return False\n'
    '        p, g = _normalize(pred), _normalize(str(gold))\n'
    '        if p == g:\n'
    '            return True\n'
    '        try:\n'
    '            pv, gv = float(p.replace(",", "")), float(g.replace(",", ""))\n'
    '            return abs(pv - gv) < 1e-6 or (gv != 0 and abs(pv - gv) / abs(gv) < 1e-5)\n'
    '        except (ValueError, OverflowError):\n'
    '            pass\n'
    '        return False\n'
    '\n'
    '    def reward_correctness(completions, answer, **kwargs):\n'
    '        return [\n'
    '            2.0 if _is_correct(_extract_boxed(c), str(a)) else 0.0\n'
    '            for c, a in zip(completions, answer)\n'
    '        ]\n'
    '\n'
    '    def reward_format(completions, **kwargs):\n'
    '        rewards = []\n'
    '        for c in completions:\n'
    '            score = 0.0\n'
    '            has_open = "<think>" in c\n'
    '            has_close = "</think>" in c\n'
    '            has_boxed = r"\\boxed{" in c\n'
    '            extracted = _extract_boxed(c)\n'
    '            if has_open and has_close:\n'
    '                score += 0.3\n'
    '                think_end = c.rfind("</think>")\n'
    '                boxed_pos = c.rfind(r"\\boxed{")\n'
    '                if boxed_pos > think_end > 0:\n'
    '                    score += 0.1\n'
    '            if has_boxed:\n'
    '                score += 0.4\n'
    '            if extracted is not None and len(extracted) > 0:\n'
    '                score += 0.2\n'
    '            rewards.append(min(score, 1.0))\n'
    '        return rewards\n'
    '\n'
    '    def reward_reasoning_length(completions, **kwargs):\n'
    '        RAMP_TO, PLATEAU_TO, DECAY_TO = 2000, 5500, 8000\n'
    '        rewards = []\n'
    '        for c in completions:\n'
    '            m = re.search(r"<think>(.*?)</think>", c, re.DOTALL)\n'
    '            n = len(m.group(1)) if m else 0\n'
    '            if n <= RAMP_TO:\n'
    '                score = 0.3 * n / RAMP_TO\n'
    '            elif n <= PLATEAU_TO:\n'
    '                score = 0.3\n'
    '            elif n <= DECAY_TO:\n'
    '                score = 0.3 * (DECAY_TO - n) / (DECAY_TO - PLATEAU_TO)\n'
    '            else:\n'
    '                score = 0.0\n'
    '            rewards.append(score)\n'
    '        return rewards\n'
    '\n'
    '    def reward_no_repetition(completions, **kwargs):\n'
    '        rewards = []\n'
    '        for c in completions:\n'
    '            words = c.split()\n'
    '            if len(words) < 30:\n'
    '                rewards.append(0.0)\n'
    '                continue\n'
    '            tail = words[-min(len(words), 200):]\n'
    '            ngrams = [tuple(tail[i : i + 6]) for i in range(len(tail) - 5)]\n'
    '            if not ngrams:\n'
    '                rewards.append(0.0)\n'
    '                continue\n'
    '            div = len(set(ngrams)) / len(ngrams)\n'
    '            if div >= 0.85:\n'
    '                rewards.append(0.1)\n'
    '            elif div >= 0.65:\n'
    '                rewards.append(0.0)\n'
    '            elif div >= 0.45:\n'
    '                rewards.append(-0.15)\n'
    '            else:\n'
    '                rewards.append(-0.3)\n'
    '        return rewards\n'
    '\n'
    '    def reward_combined(completions, answer, **kwargs):\n'
    '        cor = reward_correctness(completions, answer, **kwargs)\n'
    '        fmt = reward_format(completions, **kwargs)\n'
    '        lng = reward_reasoning_length(completions, **kwargs)\n'
    '        rep = reward_no_repetition(completions, **kwargs)\n'
    '        return [c + f + l + r for c, f, l, r in zip(cor, fmt, lng, rep)]\n'
    '\n'
    '    print("Reward functions ready (correctness 2.0 + format 1.0 + length 0.3 + rep ±).")\n'
    'else:\n'
    '    print("USE_PRETRAINED=1: skipping reward definitions.")\n'
))

