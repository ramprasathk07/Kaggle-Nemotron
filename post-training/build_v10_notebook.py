    '        seed_signs = build_seed_pairs(py_rng, POPULATION_SIZE, ANTITHETIC)\n'
    '\n'
    '        # ---- Evaluate every population member ----\n'
    '        rewards = []\n'
    '        for i, (seed, sign) in enumerate(seed_signs):\n'
    '            apply_perturbation(seed, sign)\n'
    '            try:\n'
    '                completions = generate_completions(prompt_texts)\n'
    '                r_each = reward_combined(completions, gold_answers)\n'
    '                rewards.append(float(np.mean(r_each)))\n'
    '            finally:\n'
    '                # Always undo the perturbation, even if generation failed.\n'
    '                apply_perturbation(seed, -sign)\n'
    '\n'
    '        # Free per-step intermediates.\n'
    '        torch.cuda.empty_cache()\n'
    '\n'
    '        # ---- Centered-rank normalize then apply update ----\n'
    '        rn = centered_ranks(rewards)\n'
    '\n'
    '        for buf in update_buffers:\n'
    '            buf.zero_()\n'
    '\n'
    '        for (seed, sign), r_norm in zip(seed_signs, rn):\n'
    '            # weight = r_norm · sign  (sign folds antithetic mirror back in)\n'
    '            accumulate_update(seed, float(r_norm * sign), update_buffers)\n'
