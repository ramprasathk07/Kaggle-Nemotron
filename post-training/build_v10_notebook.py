    '        dt = time.time() - step_t0\n'
    '        history.append({\n'
    '            "step": step,\n'
    '            "reward_mean": float(np.mean(rewards)),\n'
    '            "reward_max": float(np.max(rewards)),\n'
    '            "reward_min": float(np.min(rewards)),\n'
    '            "reward_std": float(np.std(rewards)),\n'
    '            "time_s": dt,\n'
    '        })\n'
    '\n'
    '        if step % LOG_EVERY == 0:\n'
